import jsPDF from "jspdf";
import type { Itinerary } from "@/lib/planner.functions";
import { formatMoney, type CurrencyCode } from "@/lib/currency";

const AZURE: [number, number, number] = [59, 130, 246];
const INK: [number, number, number] = [15, 23, 42];
const MUTED: [number, number, number] = [100, 116, 139];

export function downloadItineraryPDF(it: Itinerary, currency: CurrencyCode) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const margin = 44;
  const contentW = pageW - margin * 2;
  let y = margin;

  const setColor = (rgb: [number, number, number]) => doc.setTextColor(rgb[0], rgb[1], rgb[2]);
  const setFill = (rgb: [number, number, number]) => doc.setFillColor(rgb[0], rgb[1], rgb[2]);

  const addWatermark = () => {
    doc.saveGraphicsState();
    // @ts-expect-error jsPDF GState typing
    doc.setGState(new doc.GState({ opacity: 0.06 }));
    doc.setFont("helvetica", "bold");
    doc.setFontSize(60);
    setColor(AZURE);
    doc.text("TripGenius AI", pageW / 2, pageH / 2, { align: "center", angle: 30 });
    doc.restoreGraphicsState();
    // Footer brand line
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    setColor(MUTED);
    doc.text("Generated by TripGenius AI · tripgenius.ai", pageW / 2, pageH - 20, { align: "center" });
  };

  const newPage = () => {
    doc.addPage();
    y = margin;
    addWatermark();
  };

  const need = (h: number) => {
    if (y + h > pageH - 50) newPage();
  };

  const wrap = (text: string, size: number, style: "normal" | "bold" = "normal", color = INK, lh = 1.35) => {
    doc.setFont("helvetica", style);
    doc.setFontSize(size);
    setColor(color);
    const lines = doc.splitTextToSize(text, contentW);
    const lineH = size * lh;
    need(lines.length * lineH);
    for (const line of lines) {
      doc.text(line, margin, y);
      y += lineH;
    }
  };

  const rule = () => {
    need(14);
    setFill([226, 232, 240]);
    doc.rect(margin, y, contentW, 0.6, "F");
    y += 12;
  };

  const sectionTitle = (label: string) => {
    need(28);
    y += 6;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    setColor(AZURE);
    doc.text(label.toUpperCase(), margin, y, { charSpace: 2 });
    y += 14;
  };

  addWatermark();

  // Header
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  setColor(AZURE);
  doc.text("TRIPGENIUS AI", margin, y, { charSpace: 2 });
  y += 22;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(24);
  setColor(INK);
  const title = doc.splitTextToSize(it.destination, contentW);
  for (const line of title) { doc.text(line, margin, y); y += 26; }
  y += 4;
  wrap(it.summary, 11, "normal", MUTED, 1.45);
  rule();

  // Meta grid
  const metas: [string, string][] = [
    ["Days", String(it.days.length)],
    ["Cities", String(it.cities.length)],
    ["Est. budget", formatMoney(it.estimatedBudgetUSD, currency)],
    ["Best time", it.bestTime],
  ];
  need(46);
  const colW = contentW / metas.length;
  metas.forEach(([label, val], i) => {
    const x = margin + i * colW;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    setColor(MUTED);
    doc.text(label.toUpperCase(), x, y, { charSpace: 1.5 });
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    setColor(INK);
    const v = doc.splitTextToSize(val, colW - 8);
    doc.text(v[0] ?? "", x, y + 16);
  });
  y += 40;
  rule();

  // Route
  if (it.cities.length) {
    sectionTitle("Route");
    wrap(it.cities.join("  →  "), 11, "bold", INK);
    rule();
  }

  // Weather
  sectionTitle("Weather");
  wrap(it.weather, 10, "normal", INK);
  rule();

  // Budget
  sectionTitle("Budget breakdown");
  const bb = it.budgetBreakdown;
  const items: [string, number][] = [
    ["Stay", bb.stay], ["Food", bb.food], ["Transport", bb.transport],
    ["Activities", bb.activities], ["Misc", bb.misc],
  ];
  const total = items.reduce((s, [, v]) => s + v, 0) || 1;
  items.forEach(([label, val]) => {
    need(24);
    const pct = Math.round((val / total) * 100);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    setColor(INK);
    doc.text(label, margin, y);
    doc.text(`${formatMoney(val, currency)}  ·  ${pct}%`, margin + contentW, y, { align: "right" });
    y += 6;
    // bar bg
    setFill([226, 232, 240]);
    doc.rect(margin, y, contentW, 4, "F");
    // fill
    setFill(AZURE);
    doc.rect(margin, y, (contentW * pct) / 100, 4, "F");
    y += 14;
  });
  rule();

  // Days
  sectionTitle("Day by day");
  it.days.forEach((d) => {
    need(90);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    setColor(AZURE);
    doc.text(`DAY ${d.day}  ·  ${d.tag.toUpperCase()}  ·  ${d.city.toUpperCase()}`, margin, y, { charSpace: 1.2 });
    y += 14;
    wrap(d.title, 14, "bold", INK, 1.3);
    y += 2;
    wrap(d.description, 10, "normal", MUTED, 1.45);
    y += 4;
    const slots: [string, string][] = [
      ["Morning", d.morning], ["Afternoon", d.afternoon], ["Evening", d.evening],
    ];
    slots.forEach(([lbl, val]) => {
      need(20);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8);
      setColor(AZURE);
      doc.text(lbl.toUpperCase(), margin, y, { charSpace: 1 });
      y += 11;
      wrap(val, 10, "normal", INK, 1.4);
      y += 2;
    });
    y += 8;
    setFill([241, 245, 249]);
    doc.rect(margin, y, contentW, 0.6, "F");
    y += 10;
  });

  // Lists
  const listBlock = (label: string, rows: string[]) => {
    if (!rows.length) return;
    sectionTitle(label);
    rows.forEach((r) => {
      need(16);
      wrap(`•  ${r}`, 10, "normal", INK, 1.4);
      y += 2;
    });
    rule();
  };
  listBlock("Where to stay", it.hotels.map((h) => `${h.name} — ${h.city} · ${h.vibe} · ${formatMoney(h.pricePerNightUSD, currency)}/night`));
  listBlock("Eat here", it.restaurants.map((r) => `${r.name} — ${r.city} · ${r.cuisine}`));
  listBlock("Must-see", it.attractions.map((a) => `${a.name} — ${a.city} · ${a.type}`));
  listBlock("Hidden gems", it.hiddenGems.map((g) => `${g.name} — ${g.city} · ${g.why}`));

  const safe = it.destination.replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").toLowerCase() || "trip";
  doc.save(`tripgenius-${safe}.pdf`);
}
